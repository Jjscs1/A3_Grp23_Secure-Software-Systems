package com.evp.ballotbox;

import static org.junit.jupiter.api.Assertions.*;

import java.sql.Connection;
import java.sql.Statement;
import java.time.Clock;
import java.util.List;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;

class JdbcLogStoreTest {
    @Test
    void roundTripThroughDatabaseAndVerify() throws Exception {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:bb;DB_CLOSE_DELAY=-1;MODE=PostgreSQL");
        try (Connection c = ds.getConnection(); Statement s = c.createStatement()) {
            s.execute("CREATE TABLE ballotbox_leaf (idx BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, leaf CHAR(64) NOT NULL UNIQUE)");
            s.execute("CREATE TABLE ballotbox_checkpoint (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, alg VARCHAR(32), kid VARCHAR(64), size BIGINT, root CHAR(64), ts VARCHAR(40), sig VARCHAR(200))");
            s.execute("CREATE TABLE ballotbox_pending (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, leaf CHAR(64) NOT NULL)");
        }
        BallotBox box = new BallotBox(new JdbcLogStore(ds), CheckpointSigner.generate("bb-1"), Clock.systemUTC());
        String l1 = box.accept("r1", BallotBoxTest.env(1));
        box.accept("r2", BallotBoxTest.env(2));
        box.seal();
        box.accept("r3", BallotBoxTest.env(3));
        box.seal();
        assertTrue(box.verify().ok());
        assertTrue(box.prove(l1).isPresent());
        try (Connection c = ds.getConnection(); Statement s = c.createStatement()) {
            s.execute("UPDATE ballotbox_leaf SET leaf = '" + "aa".repeat(32) + "' WHERE idx = 1");
        }
        assertFalse(box.verify().ok());
    }

    @Test
    void sqlFileDeclaresAppendOnlyTriggers() throws Exception {
        String sql = java.nio.file.Files.readString(java.nio.file.Path.of("src/main/resources/db/sec14-ballotbox.sql"));
        assertTrue(sql.contains("BEFORE UPDATE OR DELETE ON ballotbox_leaf"));
        assertTrue(sql.contains("BEFORE TRUNCATE ON ballotbox_leaf"));
        assertTrue(sql.contains("BEFORE UPDATE OR DELETE ON ballotbox_checkpoint"));
        assertEquals(List.of(), List.of());
    }
}

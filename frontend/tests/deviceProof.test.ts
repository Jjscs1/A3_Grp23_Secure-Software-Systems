import { describe, expect, it } from 'vitest'
import { DPoPState, User, UserManager } from 'oidc-client-ts'
import { webcrypto } from 'node:crypto'
import { importJWK, jwtVerify, decodeProtectedHeader, base64url } from 'jose'

describe('device proof generated by the installed OIDC library', () => {
  it('signs a verifiable ES256 proof with a non-extractable private key', async () => {
    // jsdom does not supply subtle; use Node's real WebCrypto implementation.
    Object.defineProperty(window, 'crypto', { value: webcrypto, configurable: true })
    const keys = await crypto.subtle.generateKey(
      { name: 'ECDSA', namedCurve: 'P-256' }, false, ['sign', 'verify'],
    )
    const state = new DPoPState(keys)
    const manager = new UserManager({
      authority: 'http://localhost:8081/realms/evp', client_id: 'test',
      redirect_uri: 'http://localhost:5173/auth/callback',
      dpop: { store: {
        get: async () => state, set: async () => {},
        remove: async () => state, getAllKeys: async () => ['test'],
      } },
    })
    const user = new User({ access_token: 'bound-access-token', token_type: 'DPoP',
      profile: { sub: 'user', iss: 'issuer', aud: 'test', exp: 9999999999, iat: 1 } })
    const proof = await manager.dpopProof('http://localhost:5173/api/me', user, 'GET')
    expect(proof).toBeTruthy()
    const header = decodeProtectedHeader(proof!)
    const key = await importJWK(header.jwk!, 'ES256')
    const { payload } = await jwtVerify(proof!, key, { algorithms: ['ES256'] })
    expect(header.typ).toBe('dpop+jwt')
    expect(payload.htm).toBe('GET')
    expect(payload.htu).toBe('http://localhost:5173/api/me')
    expect(payload.ath).toBe(base64url.encode(new Uint8Array(await crypto.subtle.digest(
      'SHA-256', new TextEncoder().encode(user.access_token),
    ))))
    expect(keys.privateKey.extractable).toBe(false)
    await expect(crypto.subtle.exportKey('jwk', keys.privateKey)).rejects.toThrow()
    const next = await manager.dpopProof('http://localhost:5173/api/me', user, 'GET')
    const verified = await jwtVerify(next!, key)
    expect(verified.payload.jti).not.toBe(payload.jti)
  })
})
